#!/usr/bin/env bash
# Collect the licence texts of the modules linked into the bundled Darwin core.
# This mirrors the collection rules in scripts/build-release.sh (pre-release
# checklist B2), but reads the core inside the app bundle and writes into the
# bundle's Resources. It must run before codesign seals the app.
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../../.." && pwd)

fail() {
  echo "::error::$1"
  exit 1
}

[ "$#" -eq 1 ] || fail "usage: $(basename "$0") <MelonARC.app>"
app=$1
core="$app/Contents/MacOS/melonarc-core"
licdir="$app/Contents/Resources/licenses"
notices="$repo/THIRD-PARTY-NOTICES.md"

[ -f "$core" ] || fail "the bundled core is missing: $core"
[ -f "$notices" ] || fail "the notices index is missing: $notices"
command -v go >/dev/null 2>&1 || fail "go is required to read the bundled core's module list"

cd "$repo"
work=$(mktemp -d "${TMPDIR:-/tmp}/melonarc-licences.XXXXXX")
trap 'rm -rf "$work"' EXIT

# Which modules: the dep lines of the core we are shipping are the authority.
# Section 1 of the notices is the published index; its Darwin column must name
# exactly the same module versions before anything is copied into the bundle.
awk '
    /^## 1\./ { in1 = 1; next }
    /^## 2\./ { in1 = 0 }
    in1 && /^\| `/ {
        split($0, f, "|")
        m = f[2]; v = f[3]; darwin = f[6]
        gsub(/[` \t]/, "", m)
        gsub(/[ \t]/, "", v)
        gsub(/[ \t]/, "", darwin)
        if (darwin != "yes" && darwin != "no") exit 1
        if (m != "" && v ~ /^v/ && darwin == "yes") print m "@" v
    }
' "$notices" > "$work/declared" || fail "cannot read the Darwin column of THIRD-PARTY-NOTICES.md section 1"
LC_ALL=C sort "$work/declared" > "$work/sorted-declared" || fail "cannot sort the declared Darwin modules"
go version -m "$core" | awk '$1 == "dep" { print $2 "@" $3 }' | LC_ALL=C sort > "$work/deps" \
  || fail "cannot read the bundled core's build info"
[ -s "$work/deps" ] || fail "the bundled core reports no linked modules"
if ! cmp -s "$work/sorted-declared" "$work/deps"; then
  diff -u "$work/sorted-declared" "$work/deps" >&2 || true
  fail "THIRD-PARTY-NOTICES.md Darwin column does not match the bundled core's linked modules"
fi

# Which texts: every LICENSE/LICENCE/COPYING/NOTICE file at the root of that
# exact module version in the local Go module cache. GOPROXY=off makes an
# uncached module fail instead of downloading a text behind the build's back.
rm -rf -- "$licdir" || fail "cannot clear previous licence bundles"
mkdir -p -- "$licdir" || fail "cannot create $licdir"
nmods=0
nfiles=0
while IFS= read -r mod; do
  [ -n "$mod" ] || continue
  dir=$(GOPROXY=off GOSUMDB=off go mod download -json "$mod" 2>/dev/null |
        sed -n 's/^[[:space:]]*"Dir":[[:space:]]*"\([^"]*\)".*/\1/p')
  [ -n "$dir" ] && [ -d "$dir" ] || fail "no local module-cache copy of $mod (GOPROXY=off)"

  find "$dir" -maxdepth 1 -type f \
      \( -iname 'LICENSE*' -o -iname 'LICENCE*' -o -iname 'COPYING*' -o -iname 'NOTICE*' \) \
      -print | LC_ALL=C sort > "$work/files" || fail "cannot list licence files in $dir"
  [ -s "$work/files" ] || fail "no licence file found in $dir"

  safe=$(printf '%s' "$mod" | tr '/' '_')
  target="$licdir/$safe.txt"
  count=$(wc -l < "$work/files" | tr -d ' ')
  {
    printf 'Third-party licence texts for %s\n' "$mod"
    # Symbolic, not absolute: a shipped file must not carry a local account name.
    printf 'Source: local Go module cache, $GOMODCACHE/%s\n' "$mod"
    printf '\n'
    printf 'Generated by apps/macos/scripts/collect-core-licenses.sh (pre-release checklist B2).\n'
    printf 'Each section below is a byte-for-byte copy of the named licence\n'
    printf 'file at the root of this exact module version. The separator lines\n'
    printf 'are added by the build script and are not part of any licence text.\n'
    printf 'Files included (%s):\n' "$count"
    while IFS= read -r f; do printf '  - %s\n' "${f##*/}"; done < "$work/files"
    printf '\n'
  } > "$target" || fail "cannot write $target"

  while IFS= read -r f; do
    [ -s "$f" ] || fail "licence file is missing or empty: $f"
    printf '\n===== %s =====\n\n' "${f##*/}" >> "$target" || fail "cannot write $target"
    cat "$f" >> "$target" || fail "cannot copy $f"
    printf '\n' >> "$target" || fail "cannot write $target"
    nfiles=$((nfiles + 1))
  done < "$work/files"
  nmods=$((nmods + 1))
  printf 'collect-core-licenses: %s -> %s (%s file(s))\n' "$mod" "$safe.txt" "$count"
done < "$work/deps"
printf 'collect-core-licenses: %s module licence bundles, %s licence files\n' "$nmods" "$nfiles"
